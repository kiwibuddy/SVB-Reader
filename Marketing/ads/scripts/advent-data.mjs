/**
 * Writes src/advent/data.ts — everything the Advent ads show on the device:
 * the 26 plan rows (dates, refs, minutes, titles, notes) and the Scripture
 * turns, read straight from the app's data. Nothing on screen is retyped.
 *
 *   node scripts/advent-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(HERE, '../../../assets/data');
const read = (f) => JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8'));

const bible = read('newBibleNLT1.json');
const titles = read('SegmentTitles.json');
const times = read('SegmentReadingTimes.json');
const plan = read('ChronologicalMappings.json').adventJourneyChronological;

const COLOR = { black: 'black', red: 'red', green: 'green', blue: 'blue' };

/*
 * Flatten a block the way the reader shows it: chapter numbers inline, verse
 * numbers as superscripts and a "*" where a translation note sits. The ad
 * marks them in the text as ⟪6⟫ (chapter) and ⟦29⟧ (verse); ReaderBits draws them.
 */
const flatten = (node) => {
  if (!node || typeof node !== 'object') return '';
  if (Array.isArray(node)) return node.map(flatten).join('');
  if (node.note) return '*';
  const tags = node.tag ?? [];
  if (tags.includes('c')) return `⟪${String(node.text ?? '').trim()}⟫` + flatten(node.children);
  if (tags.includes('v')) return `⟦${String(node.text ?? '').trim()}⟧` + flatten(node.children);
  const own = typeof node.text === 'string' ? node.text : '';
  return own + flatten(node.children);
};

/** Text without the chapter and verse marks (for checks). */
const plain = (text) => text.replace(/⟪[^⟫]*⟫|⟦[^⟧]*⟧/g, '').trim();

function turns(segId) {
  return bible[segId].content.map((block) => ({
    speaker: block.source?.sourceName ?? '',
    color: COLOR[block.source?.color] ?? 'black',
    // Each child is a paragraph or a poetry line; keep them apart.
    text: (block.children || []).map(flatten).join(' ').replace(/\s+/g, ' ').replace(/\s*(⟦)/g, ' $1').replace(/⟫ ⟦/g, '⟫⟦').trim(),
  }));
}

/** Consecutive turns [from, to] of a story, checked against the expected opening words. */
function excerpt(segId, from, to, expectStart) {
  const all = turns(segId);
  const out = all.slice(from, to + 1);
  if (!plain(out[0].text).startsWith(expectStart)) {
    throw new Error(`${segId}[${from}] starts "${plain(out[0].text).slice(0, 40)}", expected "${expectStart}"`);
  }
  return out;
}

/* First Sunday of Advent: the fourth Sunday before Christmas Day. */
const YEAR = 2026;
const christmas = new Date(YEAR, 11, 25);
const start = new Date(YEAR, 11, 25 - (christmas.getDay() || 7) - 21);
const DOW = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

const rows = plan.segments.map((s, i) => {
  const d = new Date(start.getFullYear(), start.getMonth(), start.getDate() + i);
  return {
    n: i + 1,
    id: s.segmentId,
    week: s.phase,
    sunday: d.getDay() === 0,
    date: `${DOW[d.getDay()]}, ${MON[d.getMonth()]} ${d.getDate()}`, // the app's en-US short date
    ref: `${titles[s.segmentId].book[0]} ${titles[s.segmentId].ref}`,
    minutes: times[s.segmentId].estimatedReadingTimeMinutes,
    title: titles[s.segmentId].title,
    note: s.note,
  };
});
if (rows.length !== 26 || rows[25].date !== 'Thu, Dec 24') throw new Error('Advent plan no longer runs 26 days to Dec 24');

const readers = (id) => bible[id].readers;
const mix = (id) => {
  const c = bible[id].colors;
  return { black: c.black, red: c.red, green: c.green, blue: c.blue };
};
const voices = (id) => Object.keys(bible[id].sources).length;

const ui = read('UI-ENG.json').UI.chronologicalPhases.adventJourneyChronological;
const phases = Object.fromEntries(
  Object.entries(plan.phases).map(([k, v]) => [k, { title: ui[k].title, description: ui[k].description, color: v.color }])
);

const out = {
  phases,
  rows,
  annunciation: {
    id: 'S285',
    title: titles.S285.title,
    meta: `285 · ${titles.S285.book[0]} ${titles.S285.ref} · ${times.S285.estimatedReadingTimeMinutes} min`,
    readers: readers('S285'),
    mix: mix('S285'),
    voices: voices('S285'),
    lines: excerpt('S285', 10, 21, 'In the sixth month of Elizabeth'),
  },
  isaiah: {
    id: 'S191',
    title: titles.S191.title,
    meta: `191 · ${titles.S191.book[0]} ${titles.S191.ref} · ${times.S191.estimatedReadingTimeMinutes} min`,
    readers: readers('S191'),
    mix: mix('S191'),
    voices: voices('S191'),
    lines: excerpt('S191', 0, 13, 'It was in the year King Uzziah died'),
  },
};

const file = path.resolve(HERE, '../src/advent/data.ts');
fs.writeFileSync(
  file,
  `/* GENERATED by scripts/advent-data.mjs from the app's data — do not edit by hand. */\n` +
    `import type { Line } from '../data/script-gen3';\n\n` +
    `export type PlanRow = { n: number; id: string; week: 'hope' | 'peace' | 'joy' | 'love'; sunday: boolean; date: string; ref: string; minutes: number; title: string; note: string };\n` +
    `export type Story = { id: string; title: string; meta: string; readers: Array<Line['color']>; mix: Record<Line['color'], number>; voices: number; lines: Line[] };\n\n` +
    `export const PHASES: Record<PlanRow['week'], { title: string; description: string; color: string }> = ${JSON.stringify(out.phases, null, 2)};\n\n` +
    `export const ROWS: PlanRow[] = ${JSON.stringify(out.rows, null, 2)};\n\n` +
    `export const ANNUNCIATION: Story = ${JSON.stringify(out.annunciation, null, 2)};\n\n` +
    `export const ISAIAH: Story = ${JSON.stringify(out.isaiah, null, 2)};\n`
);
console.log(`wrote ${path.relative(process.cwd(), file)}`);
