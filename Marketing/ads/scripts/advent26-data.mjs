/**
 * Writes src/advent26/data.ts: every line of Scripture the Advent 2026 films
 * quote, cut from the app's Bible text (throws if one moves).
 *
 *   node scripts/advent26-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { HERE, take } from './bible-lib.mjs';

// id: [segment, turn, from, to, speaker in the data, label, reference, before, after]
const QUOTES = {
  isaiah: ['S191', 38, 'The people who walk in darkness', 'a great light.', 'The Narrator', 'The Narrator', 'Isaiah 9:2', '', ''],
  tears: ['S365', 1, 'He will wipe every tear', 'crying or pain.', 'God', 'God', 'Revelation 21:4', '', ''],
  john: ['S298', 0, 'The light shines in the darkness', 'never extinguish it.', 'The Narrator', 'The Narrator', 'John 1:5', '', ''],
  stars: ['S006', 7, 'Look up into the sky and count the stars', 'if you can.', 'God', 'God', 'Genesis 15:5', '', ''],
  wisemen: ['S266', 5, 'We saw his star as it rose', 'to worship him.', 'Some Wise Men', 'Some wise men', 'Matthew 2:2', '', ''],
  child: ['S191', 38, 'For a child is born to us', 'given to us.', 'The Narrator', 'The Narrator', 'Isaiah 9:6', '', ''],
  joy: ['S260', 27, 'He will rejoice over you with joyful songs.', 'joyful songs.', 'Zephaniah the Prophet', 'Zephaniah', 'Zephaniah 3:17', '', ''],
  peace: ['S257', 8, 'And he will be the source of peace.', 'source of peace.', 'The Narrator', 'The Narrator', 'Micah 5:5', '', ''],
  love: ['S266', 4, 'Look! The virgin will conceive a child!', 'God is with us.’', 'The Narrator', 'The Narrator', 'Matthew 1:23', '', ''],
  immanuel: ['S266', 4, 'they will call him Immanuel', 'God is with us.’', 'The Narrator', 'The Narrator', 'Matthew 1:23', '…', ''],
  savior: ['S285', 38, 'The Savior', 'the city of David!', 'An Angel', 'An angel', 'Luke 2:11', '', ''],
};

const out = {};
for (const [id, [seg, i, from, to, speaker, label, ref, before, after]] of Object.entries(QUOTES)) {
  const q = take(seg, i, from, to, speaker || undefined);
  out[id] = { text: before + q.text + after, speaker: label || q.speaker, color: q.color, ref: `${ref} NLT`, seg };
}
const ts = `// Generated by scripts/advent26-data.mjs — do not edit.
import type { Quote } from '../source/data';

export const ADVENT_QUOTES: Record<${Object.keys(out).map((k) => `'${k}'`).join(' | ')}, Quote> = ${JSON.stringify(out, null, 2)};
`;
fs.mkdirSync(path.resolve(HERE, '../src/advent26'), { recursive: true });
fs.writeFileSync(path.resolve(HERE, '../src/advent26/data.ts'), ts);
console.log(`wrote src/advent26/data.ts — ${Object.keys(out).length} quotes`);
